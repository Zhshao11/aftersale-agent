-- 种子数据（演示 / 评测 / 测试共用同一份事实来源）
--
-- ── 为什么这里全是 NOW() - INTERVAL n DAY，而不是写死日期 ──
-- 原来写的是「以 2026-09-18 为今天」的绝对日期，而政策窗口（PolicyService）是用
-- now() 和 delivered_at 算差的。种子日期不动、真实时钟往前走，两者必然错位：
-- 09-19 时「送达后 7 天内可退款」还成立，09-20 一过就变成「送达后 8 天」被拒，
-- 于是 D1 退款用例、/api/selftest、评测全员假回归——同一份代码、同一份数据，
-- 只是多过了一天。这类「测试把系统时钟当隐含输入」的写法会随日历自然腐化。
--
-- 改成相对时间后，每条订单与「现在」的间隔是恒定的，政策窗口永远自洽。
-- 配合 ON DUPLICATE KEY UPDATE（见下）每次启动刷新时间戳，可自我修复不再腐化。
--
-- 覆盖评测所需的状态矩阵：可取消/不可取消、退换窗口内外、>=500 与 <500、他人订单（越权）、已取消/已退款

