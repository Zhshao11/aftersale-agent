package com.aftersale.agent;

/**
 * 计划生成的机器可读拒绝原因。
 *
 * 为什么需要它：原先四种完全不同的失败（订单不存在 / 越权 / 政策拒绝 / 计划解析失败）
 * 在用户侧长得一模一样——都是一句「抱歉，计划生成失败」或类似的自然语言。
 * 这在排障与评测上都是致命的：无法归因，也无法统计"哪一类失败占多数"。
 *
 * 设计选择：
 * - 与 ToolErrorCode **分开**：那个是「工具契约的一部分」，会和 LLM 工具描述一起对外；
 *   这个是「编排层的失败分类」，不该出现在模型可见的契约里（否则等于告诉模型有哪些失败模式可探测）。
 * - refusalMessage 仍保留，作为给用户看的话术；refusalCode 是给机器看的。
 *   两者并存而不是替代——文案要能改，分类要稳定。
 */
public enum RefusalCode {
    /** 用户消息与对话历史里都定位不到订单 */
    ORDER_NOT_LOCATED,
    /** 订单号存在但库中查无此单 */
    ORDER_NOT_FOUND,
    /** 订单不属于当前用户 */
    FORBIDDEN,
    /** 售后政策拒绝（时间窗口/状态不符） */
    POLICY_DENIED,
    /** 规划器输出无法解析（JSON 非法 / 缺字段 / 非法工具） */
    PLAN_PARSE_FAILED
}